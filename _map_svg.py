KX = math.cos(math.radians(27))


def proj(lon, lat):
    return ((lon - 112.0) * KX * 10, (-lat - 10.0) * 10)


def path(pts):
    return 'M' + ' '.join('%.1f %.1f' % proj(*p) for p in pts) + 'Z'


